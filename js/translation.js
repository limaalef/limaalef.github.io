const LanguageManager = {
    currentLang: 'pt-BR',
    STORAGE_KEY: 'sa_lang',
    SUPPORTED: ['pt-BR', 'en'],

    _readSaved() {
        try { return localStorage.getItem(this.STORAGE_KEY); } catch { return null; }
    },

    _save(lang) {
        try { localStorage.setItem(this.STORAGE_KEY, lang); } catch { /* storage indisponível */ }
    },

    // Ordem de decisão: idioma travado pela página (ex.: admin = pt-BR)
    // → idioma salvo → idioma do navegador (pt* = português, demais = inglês).
    init() {
        const lock = document.documentElement.dataset.langLock;
        let lang;

        if (lock && this.SUPPORTED.includes(lock)) {
            lang = lock;
        } else {
            const saved = this._readSaved();
            if (this.SUPPORTED.includes(saved)) {
                lang = saved;
            } else {
                const browserLang = (navigator.language || navigator.userLanguage || 'pt-BR').toLowerCase();
                lang = browserLang.startsWith('pt') ? 'pt-BR' : 'en';
            }
        }

        this.setLanguage(lang, false, false); // sem re-render e sem gravar (não foi escolha do usuário)
    },

    // persist=true grava a escolha para as próximas páginas.
    setLanguage(lang, rerender = true, persist = true) {
        if (!this.SUPPORTED.includes(lang)) lang = 'pt-BR';
        this.currentLang = lang;
        window.appLang = lang;
        document.documentElement.lang = lang;
        if (persist && !document.documentElement.dataset.langLock) this._save(lang);

        const flag = document.getElementById('langFlag');
        if (flag) flag.textContent = lang === 'pt-BR' ? '🇧🇷' : '🇺🇸';

        this.updateAllTexts(rerender);
        if (rerender) {
            document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
        }
    },

    getLanguage() {
        if (this.currentLang === 'en') {
            return 'en-US'
        } else {
            return 'pt-BR'
        }
    },

    t(key) {
        return translations[this.currentLang][key] || key;
    },

    updateAllTexts(rerender = true) {
        // Atualiza elementos com data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            
            if (el.tagName === 'INPUT') {
                el.placeholder = translation;
            } else if (el.tagName === 'OPTION') {
                el.textContent = translation;
            } else {
                el.textContent = translation;
            }
        });

        // Rótulos acessíveis traduzidos (aria-label)
        document.querySelectorAll('[data-i18n-aria]').forEach(el => {
            el.setAttribute('aria-label', this.t(el.getAttribute('data-i18n-aria')));
        });

        // Atualiza placeholders especiais
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.placeholder = this.t(key);
        });

        // Atualiza info de página
        this.updatePageInfo();

        // Re-renderiza a listagem atual (se houver) quando o idioma muda
        if (rerender && typeof AppState !== 'undefined' && typeof Renderer !== 'undefined'
            && AppState.filteredMatches && AppState.filteredMatches.length > 0
            && document.getElementById('matchesContainer')) {
            Renderer.render();
        }
    },

    updatePageInfo() {
        const pageInfo = document.getElementById('pageInfo');
        if (pageInfo && typeof AppState !== 'undefined') {
            pageInfo.textContent = `${this.t('page')} ${AppState.currentPage} ${this.t('of')} ${AppState.totalPages}`;
        }
    },

    translateText(text) {
        if (!text) return text;
        
        // Tenta encontrar tradução exata
        const translation = this.t(text);
        if (translation !== text) return translation;
        
        // Se não encontrar tradução exata, tenta traduzir partes conhecidas
        if (this.currentLang === 'en') {
            // Traduz padrões de rodadas
            if (text.includes('Disputa 3º Lugar')) {
                return `Play-off for 3rd place`;
            }
            
            let leg = '';
            if (text.includes('Ida')) {
                leg = ' - 1st Leg';
            } else if (text.includes('Volta')) {
                leg = ' - 2nd Leg';
            }

            if (text.includes('Oitavas de Final')) {
                return `Round of 16${leg}`;
            } else if (text.includes('Quartas de Final')) {
                return `Quarterfinals${leg}`;
            } else if (text.includes('Semifinal') || text.includes('Semifinais')) {
                return `Semifinals${leg}`;
            } else if (text.includes('Final')) {
                return `Final${leg}`;
            }

            const roundMatch = text.match(/(\d+)ª Rodada/);
            if (roundMatch) {
                const number = roundMatch[1];
                const suffix = this.getOrdinalSuffix(number);
                return `Round ${number}`;
            }

            const phaseMatch = text.match(/(\d+)ª Fase/);
            if (roundMatch) {
                const number = roundMatch[1];
                const suffix = this.getOrdinalSuffix(number);
                return `Phase ${number}`;
            }
        }
        
        return text;
    },

    translateOrdinary(num, type) {
        if (this.currentLang === 'en') {
            return (String(num) + this.getOrdinalSuffix(num))
        } else {
            if (type === 'fem') {
                return (String(num) + 'ª')
            } else {
                return (String(num) + 'º')
            }
        }
    },
    
    getOrdinalSuffix(num) {
        const n = parseInt(num);
        const s = ["th", "st", "nd", "rd"];
        const v = n % 100;
        return s[(v - 20) % 10] || s[v] || s[0];
    }
};
